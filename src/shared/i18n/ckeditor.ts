const CKEDITOR_PLURAL_FORMS: Record<UiLanguage, (count: number) => number> = {
    fr: (count) => (count > 1 ? 1 : 0),
    en: (count) => (count !== 1 ? 1 : 0),
    es: (count) => (count !== 1 ? 1 : 0),
    pt: (count) => (count !== 1 ? 1 : 0),
    sw: (count) => (count !== 1 ? 1 : 0),
};

const SUPPORTED_LANGUAGES: UiLanguage[] = ['fr', 'en', 'es', 'pt', 'sw'];

function buildDictionary(language: UiLanguage): CkeditorDictionary {
    return Object.fromEntries(
        Object.entries(CKEDITOR_TRANSLATIONS).map(([key, translations]) => [
            key,
            translations[language] ?? translations.en,
        ]),
    );
}

export function registerAllCkeditorTranslations(): void {
    const ckeditorGlobal = globalThis as CkeditorGlobal;
    const registry = (ckeditorGlobal.CKEDITOR_TRANSLATIONS ??= {});

    for (const language of SUPPORTED_LANGUAGES) {
        const existing = registry[language] ?? { dictionary: {} };
        registry[language] = {
            ...existing,
            dictionary: {
                ...existing.dictionary,
                ...buildDictionary(language),
            },
            getPluralForm: CKEDITOR_PLURAL_FORMS[language],
        };
    }
}
